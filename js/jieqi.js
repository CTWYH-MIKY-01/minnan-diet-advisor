/* 计算某年某节气的日期 */
function jqDate(year, def) {
  const Y = year % 100;
  let day = Math.floor(Y * 0.2422 + def.c) - Math.floor((Y - 1) / 4);
  if (day < 1) day = 1;
  return new Date(year, def.m - 1, day);
}

/* 生成某年全部节气（含起止日期与所属季节） */
function yearJieqi(year) {
  const out = JQ_DEF.map(function (d, i) {
    const start = jqDate(year, d);
    const next = JQ_DEF[(i + 1) % 24];
    const nextStart = (i === 23) ? jqDate(year + 1, next) : jqDate(year, next);
    return {
      name: d.n, season: d.s, start: start,
      end: new Date(nextStart.getTime() - 86400000),
      tiaoli: d.tiaoli || "",
    };
  });
  return out;
}

/* 统一入参：Date 或时间戳数字都转成 Date */
function toDate(v) {
  if (v instanceof Date) return v;
  if (typeof v === "number") return new Date(v);
  if (typeof v === "string") return new Date(v.replace(/-/g, "/"));
  return new Date();
}

/* 查某天属于哪个节气 */
function currentJieqi(date) {
  date = toDate(date);
  const y = date.getFullYear();
  const list = yearJieqi(y).concat(yearJieqi(y + 1));
  for (let i = 0; i < list.length; i++) {
    if (date >= list[i].start && date <= list[i].end) return list[i];
  }
  return list[0];
}

/* 取下一个节气（用于「即将到来」提示） */
function nextJieqi(date) {
  date = toDate(date);
  const list = yearJieqi(date.getFullYear()).concat(yearJieqi(date.getFullYear() + 1));
  for (let i = 0; i < list.length; i++) {
    if (list[i].start > date) return list[i];
  }
  return list[0];
}


/* ---------- BMI ---------- */
function bmiOf(height, weight) {
  if (!height || !weight) return null;
  return (weight / Math.pow(height / 100, 2));
}
function bmiAdvice(bmi) {
  if (bmi === null) return "";
  if (bmi < 18.5) return "偏瘦：适当加餐、加蛋加鱼，不必刻意限食";
  if (bmi < 24) return "正常：保持现有饮食节奏";
  if (bmi < 28) return "超重：主食减 1/4，晚餐少油，饭后快走 30 分钟";
  return "偏胖：主食减半、戒甜饮，七分饱，配合运动";
}

